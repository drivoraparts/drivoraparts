#!/usr/bin/env python3
"""Master tracker for the 120-product expansion, generated from pipeline.json.

    python3 scripts/build-hv120-tracker.py

Writes docs/catalog-expansion/high-value-120/TRACKER.md: per candidate, the pipeline stages (discovered, technical
verification, retail price verification, image provenance, import readiness, published) and the live URL. A product
counts toward the 120 only when it is LIVE VERIFIED.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DIR = os.path.join(ROOT, "docs/catalog-expansion/high-value-120")
d = json.load(open(os.path.join(DIR, "pipeline.json")))
ORDER = ["tires", "transmissions", "steering", "turbochargers", "engines", "seats"]
STAGE = {  # status -> (technical, price, image, import ready, published)
    "LIVE VERIFIED": ("yes", "yes", "yes", "yes", "LIVE"), "READY": ("yes", "yes", "yes", "yes", "pending deploy"),
    "IMPORTED": ("yes", "yes", "yes", "yes", "pending"), "MERGED": ("yes", "yes", "yes", "yes", "pending"),
    "DEPLOYED": ("yes", "yes", "yes", "yes", "pending check"), "IMAGE PENDING": ("yes", "yes", "no", "no", "no"),
    "PRICE VERIFIED": ("partial", "yes", "no", "no", "no"), "FITMENT VERIFIED": ("yes", "no", "no", "no", "no"),
    "RESEARCH": ("partial", "partial", "no", "no", "no"), "DISCOVERED": ("no", "no", "no", "no", "no"),
    "REJECTED": ("-", "-", "-", "no", "rejected"),
}
rows, live = [], {c: 0 for c in ORDER}
for p in d["products"]:
    st = p["status"]
    t = STAGE.get(st, ("?", "?", "?", "?", st))
    url = f"https://drivoraparts.com/product/{p['liveId']}" if p.get("liveId") else ""
    if st == "LIVE VERIFIED" and p["category"] in live:
        live[p["category"]] += 1
    rows.append((ORDER.index(p["category"]) if p["category"] in ORDER else 9, p, st, t, url))
rows.sort(key=lambda r: (r[0], r[2] != "LIVE VERIFIED", r[1].get("liveId") or 0))
out = ["# 120-product expansion: master tracker", "",
       "Generated by `scripts/build-hv120-tracker.py` from `pipeline.json`. Only LIVE VERIFIED rows count toward the 120.", "",
       "| Category | Target | Live verified | Remaining |", "|---|---|---|---|"]
for c in ORDER:
    out.append(f"| {c} | 20 | {live[c]} | {max(0, 20 - live[c])} |")
tot = sum(live.values())
out += [f"| **Total** | 120 | **{tot}** | **{120 - tot}** |", "",
        "| Category | Product | Part no. | Status | Technical | Retail price | Image provenance | Import ready | Published | Live URL |",
        "|---|---|---|---|---|---|---|---|---|---|"]
for _, p, st, t, url in rows:
    prod = (p.get("manufacturer", "") + " " + p.get("product", "")).strip().replace("|", "/")
    out.append(f"| {p['category']} | {prod} | {p.get('partNumber','')} | {st} | {t[0]} | {t[1]} | {t[2]} | {t[3]} | {t[4]} | {url} |")
open(os.path.join(DIR, "TRACKER.md"), "w").write("\n".join(out) + "\n")
print(f"tracker: {len(rows)} rows, {tot} live verified")
