/**
 * Writes lib/inventory/data/catalog-snapshot.json: the raw records of the
 * public (Toyota) listings, which is all the deployed site loads. Run before
 * every build (npm "prebuild" and pages:build) so the snapshot always matches
 * the source catalog and lib/inventory/data/toyota-catalog.json.
 *
 *   node scripts/build-catalog-snapshot.mjs           write the snapshot
 *   node scripts/build-catalog-snapshot.mjs --check   fail if it is stale
 *
 * See lib/inventory/full-catalog.ts for why the full catalog is not deployed.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "lib/inventory/data/catalog-snapshot.json");
const CHECK = process.argv.includes("--check");

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "drivora-snapshot-"));
const entry = path.join(tmp, "entry.ts");
const bundle = path.join(tmp, "entry.mjs");

fs.writeFileSync(
  entry,
  `import { rawProductCatalog } from "@/lib/inventory/full-catalog";
import { CHECKOUT_TEST_PRODUCT_ID } from "@/lib/inventory/pricing";
import toyota from "@/lib/inventory/data/toyota-catalog.json";
const keep = new Set([...toyota.visible, CHECKOUT_TEST_PRODUCT_ID]);
const records = rawProductCatalog.filter((p) => keep.has(p.id));
const archivedIds = rawProductCatalog.filter((p) => !keep.has(p.id)).map((p) => p.id).sort((a, b) => a - b);
process.stdout.write(JSON.stringify({ total: rawProductCatalog.length, records, archivedIds }));
`
);

const { build } = await import("esbuild");
await build({
  entryPoints: [entry],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: bundle,
  loader: { ".json": "json" },
  alias: { "@": ROOT },
  logLevel: "error",
  absWorkingDir: ROOT,
});
const raw = execFileSync(process.execPath, ["--max-old-space-size=4096", bundle], {
  cwd: ROOT,
  maxBuffer: 256 * 1024 * 1024,
  encoding: "utf8",
});
fs.rmSync(tmp, { recursive: true, force: true });

const { total, records, archivedIds } = JSON.parse(raw);

/*
 * createdAt on a large part of the source catalog is computed when the module
 * loads (Date.now() plus a day), so it differs on every run. Those values are
 * pinned to what the previous snapshot recorded, so regenerating an unchanged
 * catalog produces an identical file and --check stays meaningful.
 */
const previous = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, "utf8")) : null;
const previousCreated = new Map((previous?.records ?? []).map((r) => [r.id, r.createdAt]));
const DAY = 24 * 60 * 60 * 1000;
for (const record of records) {
  const before = previousCreated.get(record.id);
  if (before != null && Math.abs((record.createdAt ?? 0) - Date.now() - DAY) < 10 * 60 * 1000) {
    record.createdAt = before;
  }
}

const snapshot = {
  _comment:
    "Generated by scripts/build-catalog-snapshot.mjs from lib/inventory/full-catalog.ts. Do not edit: change the source listing and rebuild.",
  records,
  archivedIds,
};
const text = JSON.stringify(snapshot) + "\n";

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("❌ lib/inventory/data/catalog-snapshot.json is stale. Run: node scripts/build-catalog-snapshot.mjs");
    process.exit(1);
  }
  console.log(`✓ Catalog snapshot is current (${records.length} of ${total} listings deployed)`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(
    `✓ Catalog snapshot: ${records.length} of ${total} listings deployed, ${archivedIds.length} kept in source only (${(text.length / 1024).toFixed(0)} KB)`
  );
}
