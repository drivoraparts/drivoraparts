#!/usr/bin/env python3
"""Live progress report for the Toyota catalog expansion (900-product target).

    python3 scripts/build-catalog-progress.py

Counts staged research records (docs/catalog-expansion/toyota-expansion-batch-*.json)
and live storefront listings separately, and writes
docs/catalog-expansion/catalog-progress.md.
"""
import glob
import json
import re
from collections import Counter, defaultdict

MODELS = ["RAV4", "Tacoma", "Camry", "Highlander", "Tundra", "4Runner", "Corolla", "Sequoia", "Sienna"]
TARGET = 100
DIR = "docs/catalog-expansion"

records = []
for f in sorted(glob.glob(f"{DIR}/toyota-expansion-batch-*.json")):
    if not re.search(r"batch-\d+\.json$", f):
        continue
    for r in json.load(open(f, encoding="utf-8"))["records"]:
        r["_batch"] = re.search(r"batch-(\d+)", f).group(1)
        records.append(r)


def status(r):
    if r.get("audit", {}).get("primaryStatus", "").startswith("Rejected"):
        return "REJECTED"
    if r.get("status") == "ready" and r.get("pricing", {}).get("approved"):
        return "VERIFIED / READY"
    return "REVIEW REQUIRED"


seen, dup = set(), 0
per_model = defaultdict(Counter)
per_cat = Counter()
st = Counter()
priced = 0
for r in records:
    key = r["partNumber"] or f"engine:{r['engines']}"
    if key in seen:
        dup += 1
        continue
    seen.add(key)
    s = status(r)
    st[s] += 1
    per_cat[r.get("proposedCategoryName") or r.get("proposedCategory")] += 1
    if r.get("pricing", {}).get("recommendedPrice") is not None:
        priced += 1
    models = {a["model"] for a in r.get("fitmentApplications", [])} or {a["model"] for a in r.get("fitmentVerification", {}).get("applications", [])}
    for m in models:
        if m in MODELS:
            per_model[m]["records"] += 1
            if r.get("fitmentApplications"):
                per_model[m]["listed fitment"] += 1
            if s == "VERIFIED / READY":
                per_model[m]["ready"] += 1
            if (r.get("pricing", {}).get("recommendedPrice") or 0) >= 200 or any(c.get("price", 0) >= 200 for c in r.get("pricing", {}).get("competitors", [])):
                per_model[m]["$200+"] += 1

imported = json.load(open("lib/inventory/data/toyota-genuine-oem.json", encoding="utf-8"))
live = json.load(open("lib/inventory/data/catalog-snapshot.json", encoding="utf-8"))["records"]
fv = Counter(a["status"] for r in records for a in r.get("fitmentVerification", {}).get("applications", []))

md = ["# Toyota Catalog Expansion — Progress\n",
      "Generated by `scripts/build-catalog-progress.py`. **Research records are staged files, not storefront listings.**\n",
      "## Totals\n", "| Measure | Count |", "|---|---|",
      f"| Unique products researched (staged) | {len(seen)} |",
      f"| Duplicates across batches | {dup} |",
      f"| VERIFIED / READY | {st['VERIFIED / READY']} |",
      f"| REVIEW REQUIRED | {st['REVIEW REQUIRED']} |",
      f"| REJECTED | {st['REJECTED']} |",
      f"| With 3+ attributed competitor prices and a 3-5% target | {priced} |",
      "| Supplier costs established | 0 |",
      f"| Toyota catalog images integrated | {sum(len(p['images']) for p in imported)} (for {len(imported)} products) |",
      f"| Fitment applications: verified / VIN-dependent / unresolved / removed | {fv['verified']} / {fv['vin_dependent']} / {fv['unresolved']} / {fv['removed']} |",
      f"| Live storefront listings (unchanged) | {len(live)} |",
      f"| New products integrated into the storefront | {len(imported)} ({', '.join(str(p['id']) for p in imported)}) |", "",
      "## By model (target 100 each)\n", "| Model | Staged records | With listed fitment | $200+ | Ready | Progress |", "|---|---|---|---|---|---|"]
for m in MODELS:
    c = per_model[m]
    md.append(f"| {m} | {c['records']} | {c['listed fitment']} | {c['$200+']} | {c['ready']} | {c['records']}/{TARGET} |")
md += ["", "A record that fits several models counts once per model.\n", "## By category\n", "| Category | Records |", "|---|---|"]
for k, v in per_cat.most_common():
    md.append(f"| {k} | {v} |")
md += ["", "## Data sources\n", "See `data-sources-assessment.md` for every source tested, what it provides, and the authorizations that would unlock supplier cost, licensed images and EPC-scale fitment.\n"]
open(f"{DIR}/catalog-progress.md", "w", encoding="utf-8").write("\n".join(md) + "\n")
print("unique:", len(seen), dict(st), "| per model:", {m: per_model[m]["records"] for m in MODELS})
